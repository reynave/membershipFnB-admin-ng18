#!/usr/bin/env node
/**
 * Generate build version code for the admin app.
 *
 * Output file : src/environments/version.ts
 * Format      : YYMMDDHHmm (local time), e.g. 2611171623 => 2026-11-17 16:23
 *
 * Usage:
 *   node scripts/generate-version.js
 *   APP_VERSION=2611171623 node scripts/generate-version.js   <- override (CI)
 *
 * This script is executed automatically by the npm "prebuild" / "prestart" /
 * "prewatch" hooks, so `npm run build` always embeds the current version code.
 */
const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const outputFile = path.join(projectRoot, 'src', 'environments', 'version.ts');

const pad = (value) => String(value).padStart(2, '0');

/**
 * Build version code in YYMMDDHHmm format (10 digits).
 * Example: 2026-11-17 16:23 -> "2611171623"
 */
function createVersionCode(date = new Date()) {
  return (
    pad(date.getFullYear() % 100) +
    pad(date.getMonth() + 1) +
    pad(date.getDate()) +
    pad(date.getHours()) +
    pad(date.getMinutes())
  );
}

function main() {
  const now = new Date();
  const override = (process.env.APP_VERSION || '').trim();
  const versionCode = override || createVersionCode(now);

  if (!/^\d{10}$/.test(versionCode)) {
    console.error(
      `[version] Invalid version code "${versionCode}". Expected 10 digits (YYMMDDHHmm).`
    );
    process.exit(1);
  }

  const content = `// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY.
// Generated by scripts/generate-version.js
// Format: YYMMDDHHmm (e.g. 2611171623)
export const APP_VERSION = '${versionCode}';
export const APP_BUILD_TIME = '${now.toISOString()}';
`;

  fs.mkdirSync(path.dirname(outputFile), { recursive: true });

  const previous = fs.existsSync(outputFile)
    ? fs.readFileSync(outputFile, 'utf8')
    : '';

  if (previous === content) {
    console.log(`[version] ${versionCode} (unchanged)`);
  } else {
    fs.writeFileSync(outputFile, content, 'utf8');
    console.log(
      `[version] ${versionCode} -> ${path.relative(projectRoot, outputFile)}`
    );
  }
}

if (require.main === module) {
  main();
}

module.exports = { createVersionCode };
